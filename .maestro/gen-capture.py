#!/usr/bin/env python3
"""Writes capture.yaml: the walk through the five tabs.

Each tab: tap it, scroll to the top, screenshot, then measured scrolls down with
a screenshot after each. The shot counts are generous on purpose so that even
the smallest phone (iPhone SE) reaches the bottom; capture.sh then deletes the
repeated frames at the end of each tab, so a tall phone keeps fewer files.

Run after changing a count:  python3 .maestro/gen-capture.py
"""
from pathlib import Path

# (order, name, x position of the tab in the tab bar, screenshots)
TABS = [
    (1, "home", "10%", 14),
    (2, "habits", "30%", 5),
    (3, "journal", "50%", 4),
    (4, "goals", "70%", 4),
    (5, "settings", "90%", 9),
]
TO_TOP = 8  # quick swipes down to reach the top, whatever the tab remembers
# They start at 50 %: higher up, Goals has fixed buttons (Add Goal, Template,
# Reorder) over its list – on the iPhone SE a swipe from 30 % never moved it.

out = [
    "appId: com.petrturek.selfrise",
    "---",
    "# GENERATED by gen-capture.py – edit that file, not this one.",
    "# Walk the five tabs: scroll each to the top, screenshot, then measured scrolls",
    "# down with a screenshot after each. Taps by position (works on all sizes).",
    "# Fresh demo data first: it is dated from today, so every run shows the same state.",
    "- runFlow: demo-data.yaml",
]


def swipe(start: str, end: str, ms: int) -> None:
    out.extend(
        [
            "- swipe:",
            f'    start: "{start}"',
            f'    end: "{end}"',
            f"    duration: {ms}",
        ]
    )


for order, name, x, shots in TABS:
    out += ["- tapOn:", f'    point: "{x},94%"', "- waitForAnimationToEnd"]
    for _ in range(TO_TOP):
        swipe("50%,50%", "50%,90%", 300)
    out.append("- waitForAnimationToEnd")
    for n in range(1, shots + 1):
        if n > 1:
            swipe("50%,75%", "50%,35%", 600)
            out.append("- waitForAnimationToEnd")
        out.append(f"- takeScreenshot: ${{OUT}}/{order}-{name}-{n:02d}")

# Leave the app where it started.
out += ["- tapOn:", '    point: "10%,94%"', "- waitForAnimationToEnd"]

Path(__file__).with_name("capture.yaml").write_text("\n".join(out) + "\n")
print("capture.yaml:", sum(t[3] for t in TABS), "screenshots")
